    #[test]
    fn rne_matches_half_oracle_around_every_positive_finite_midpoint() {
        for lower_bits in 0u16..0x7bff {
            let lower = Float16::from_bits(lower_bits).to_f32();
            let upper = Float16::from_bits(lower_bits + 1).to_f32();
            let midpoint = (lower + upper) * 0.5;
            let probes = [
                f32::from_bits(midpoint.to_bits().saturating_sub(1)),
                midpoint,
                f32::from_bits(midpoint.to_bits().saturating_add(1)),
            ];
            for probe in probes {
                assert_eq!(
                    f32_to_f16_rne_bits(probe),
                    Ok(Float16::from_f32(probe).to_bits()),
                    "lower f16 bits {lower_bits:#06x}, probe {probe:?}"
                );
                assert_eq!(
                    f32_to_f16_rne_bits(-probe),
                    Ok(Float16::from_f32(-probe).to_bits()),
                    "negative lower f16 bits {lower_bits:#06x}, probe {:?}",
                    -probe
                );
            }
        }
    }

