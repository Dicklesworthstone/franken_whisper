    #[test]
    fn checkpoint_hash_observes_every_chunk_and_the_terminal_boundary() {
        use std::sync::atomic::{AtomicUsize, Ordering};

        let bytes = vec![0x5a; CHECKPOINT_CHUNK_BYTES + 1];
        let successful_calls = AtomicUsize::new(0);
        let digest = sha256_bytes_with_checkpoint(&bytes, &|| {
            successful_calls.fetch_add(1, Ordering::SeqCst);
            Ok(())
        })
        .expect("hash with checkpoints");
        assert_eq!(digest, sha256_bytes(&bytes));
        assert_eq!(successful_calls.load(Ordering::SeqCst), 3);

        for cancel_at in 0..3 {
            let calls = AtomicUsize::new(0);
            let error = sha256_bytes_with_checkpoint(&bytes, &|| {
                if calls.fetch_add(1, Ordering::SeqCst) == cancel_at {
                    Err(FwError::Cancelled("synthetic stop".to_owned()))
                } else {
                    Ok(())
                }
            })
            .expect_err("each hash checkpoint must be cancellation-observable");
            assert!(matches!(error, FwError::Cancelled(_)));
            assert_eq!(calls.load(Ordering::SeqCst), cancel_at + 1);
        }

        let calls = AtomicUsize::new(0);
        let error = sha256_bytes_with_checkpoint(&[], &|| {
            calls.fetch_add(1, Ordering::SeqCst);
            Err(FwError::Cancelled("synthetic empty-input stop".to_owned()))
        })
        .expect_err("empty input must still observe the terminal checkpoint");
        assert!(matches!(error, FwError::Cancelled(_)));
        assert_eq!(calls.load(Ordering::SeqCst), 1);
    }

