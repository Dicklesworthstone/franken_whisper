fn sha256_bytes(bytes: &[u8]) -> String {
    let mut hasher = Sha256::new();
    hasher.update(bytes);
    format!("{:x}", hasher.finalize())
}

fn sha256_bytes_with_checkpoint(
    bytes: &[u8],
    checkpoint: &(dyn Fn() -> FwResult<()> + Sync),
) -> FwResult<String> {
    let mut hasher = Sha256::new();
    for chunk in bytes.chunks(CHECKPOINT_CHUNK_BYTES) {
        downcast_checkpoint(checkpoint)?;
        hasher.update(chunk);
    }
    downcast_checkpoint(checkpoint)?;
    Ok(format!("{:x}", hasher.finalize()))
}

fn canonical_json_bytes<T: Serialize>(value: &T) -> FwResult<Vec<u8>> {
    let value = serde_json::to_value(value)?;
    let mut output = Vec::new();
    write_lexicographic_json(&value, &mut output)?;
    Ok(output)
}

fn write_lexicographic_json(value: &serde_json::Value, output: &mut Vec<u8>) -> FwResult<()> {
    match value {
        serde_json::Value::Null
        | serde_json::Value::Bool(_)
        | serde_json::Value::Number(_)
        | serde_json::Value::String(_) => serde_json::to_writer(output, value)?,
        serde_json::Value::Array(values) => {
            output.push(b'[');
            for (index, item) in values.iter().enumerate() {
                if index != 0 {
                    output.push(b',');
                }
                write_lexicographic_json(item, output)?;
            }
            output.push(b']');
        }
        serde_json::Value::Object(values) => {
            output.push(b'{');
            let mut keys = values.keys().collect::<Vec<_>>();
            keys.sort_unstable();
            for (index, key) in keys.into_iter().enumerate() {
                if index != 0 {
                    output.push(b',');
                }
                serde_json::to_writer(&mut *output, key)?;
                output.push(b':');
                write_lexicographic_json(&values[key], output)?;
            }
            output.push(b'}');
        }
    }
    Ok(())
}

fn downcast_error(code: &str, message: &str) -> FwError {
    FwError::InvalidRequest(format!("sortformer_f16_downcast.{code}: {message}"))
}

